#!/usr/bin/env python3
"""
gen_lfo_table.py - generate fpga/rtl/lfo_sine_pkg.vhd: the quarter-wave sine
table of the generated LFO (nco_lfo.vhd, v2 step D1).

    SINE_Q(k) = round(32767 * sin(pi/2 * k / 256)),  k = 0 .. 256

257 entries so that the last interpolation interval has its end point. The
Python reference model (sim/cocotb/lfo_model.py) imports SINE_Q from here.

    python3 tools/gen_lfo_table.py
"""
import math
import os

N = 256
SINE_Q = [round(32767 * math.sin(math.pi / 2 * k / N)) for k in range(N + 1)]

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "fpga", "rtl", "lfo_sine_pkg.vhd")


def main():
    rows = []
    for i in range(0, N + 1, 8):
        rows.append("    " + ", ".join("%5d" % v for v in SINE_Q[i:i + 8]))
    text = """-- Generated by tools/gen_lfo_table.py - do not edit.
-- Quarter-wave sine table of the generated LFO (nco_lfo.vhd, v2 step D1):
-- SINE_Q(k) = round(32767 * sin(pi/2 * k / 256)), k = 0 .. 256.
package lfo_sine_pkg is
  type sine_q_t is array (0 to {n}) of integer range 0 to 32767;
  constant SINE_Q : sine_q_t := (
{rows});
end package;
""".format(n=N, rows=",\n".join(rows))
    with open(OUT, "w", newline="\n") as f:
        f.write(text)
    print("wrote %s (%d entries)" % (os.path.relpath(OUT), N + 1))


if __name__ == "__main__":
    main()
