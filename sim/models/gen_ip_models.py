#!/usr/bin/env python3
"""
gen_ip_models.py - generate simulation replacements for the Intel IP wrappers.

For every megafunction wrapper in fpga/ip/*.vhd (altsyncram ROM / dual-port
RAM, dcfifo) this writes sim/models/ip/<name>.vhd: an entity with the same name
and ports whose architecture instantiates the behavioural model (sim_rom,
sim_dpram, sim_dcfifo). Simulators without altera_mf (GHDL) compile these
instead of fpga/ip/*.vhd.

    python3 sim/models/gen_ip_models.py
"""
import os
import re
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
IP_DIR = os.path.join(ROOT, "fpga", "ip")
OUT_DIR = os.path.join(ROOT, "sim", "models", "ip")

HEADER = """-- Generated by sim/models/gen_ip_models.py from fpga/ip/{src} - do not edit.
-- Simulation replacement for the Intel megafunction ({kind}).
library ieee;
use ieee.std_logic_1164.all;

"""


def param(text, name):
    m = re.search(r"\b%s\s*=>\s*\"?([^\",\s)]+)\"?" % name, text)
    return m.group(1) if m else None


def entity_block(text, name):
    m = re.search(r"(ENTITY\s+%s\s+IS.*?END\s+%s\s*;)" % (name, name), text, re.S | re.I)
    if not m:
        sys.exit("cannot find entity %s" % name)
    return m.group(1)


def main():
    os.makedirs(OUT_DIR, exist_ok=True)
    n = 0
    for fn in sorted(os.listdir(IP_DIR)):
        if not fn.endswith(".vhd"):
            continue
        src = open(os.path.join(IP_DIR, fn), encoding="latin-1").read()
        name = fn[:-4]
        mode = param(src, "operation_mode")
        if mode == "ROM":
            kind = "altsyncram ROM"
            has_rden = re.search(r"\brden\s*:\s*IN", src, re.I) is not None
            body = """ARCHITECTURE sim OF {name} IS
BEGIN
  m : entity work.sim_rom
    generic map (WIDTH => {w}, ADDR_W => {aw}, DEPTH => {d}, INIT_FILE => "{f}")
    port map (clock => clock, address => address, rden => {rden}, q => q);
END sim;
""".format(name=name, w=param(src, "width_a"), aw=param(src, "widthad_a"),
           d=param(src, "numwords_a"), f=param(src, "init_file"),
           rden="rden" if has_rden else "'1'")
        elif mode == "DUAL_PORT":
            kind = "altsyncram dual-port RAM"
            body = """ARCHITECTURE sim OF {name} IS
BEGIN
  m : entity work.sim_dpram
    generic map (WIDTH => {w}, ADDR_W => {aw})
    port map (clock => clock, data => data, rdaddress => rdaddress,
              wraddress => wraddress, wren => wren, q => q);
END sim;
""".format(name=name, w=param(src, "width_a"), aw=param(src, "widthad_a"))
        elif param(src, "lpm_numwords"):
            kind = "dcfifo"
            body = """ARCHITECTURE sim OF {name} IS
BEGIN
  m : entity work.sim_dcfifo
    generic map (WIDTH => {w}, DEPTH => {d})
    port map (data => data, rdclk => rdclk, rdreq => rdreq, wrclk => wrclk,
              wrreq => wrreq, q => q, rdempty => rdempty, wrfull => wrfull);
END sim;
""".format(name=name, w=param(src, "lpm_width"), d=param(src, "lpm_numwords"))
        else:
            print("skipping %s (unknown megafunction)" % fn)
            continue
        with open(os.path.join(OUT_DIR, fn), "w", newline="\n") as f:
            f.write(HEADER.format(src=fn, kind=kind))
            f.write(entity_block(src, name) + "\n\n" + body)
        print("%-20s -> %s" % (fn, kind))
        n += 1
    print("%d models written to %s" % (n, os.path.relpath(OUT_DIR, ROOT)))


if __name__ == "__main__":
    main()
