-- -----------------------------------------------------------------------------
-- level_gain.vhd  (v2 step D6)
-- Output level of the overdrive / distortion: signed level L in Q8 log2 units
-- (1 unit = 1/256 of a factor 2 = 0.02352 dB, the unit of the dynamics thresholds),
-- clamped to -1024 .. +512 (-24.08 ... +12.04 dB), converted to a linear gain
--     G = mant * 2^n / 2^16,   n = L >> 8 (floor, -4 .. +2),  f = L & 255,
--     mant = round(2^(f/256) * 2^16)   (256-entry table, 65536 .. 130 4xx, 17 bit)
-- Outputs mant and the right-shift sh = 16 - n (14 .. 20) of the product x * mant:
--     y = floor(x * mant / 2^sh)  = floor(x * G).
-- L = 0 gives mant = 65536, sh = 16: y = x exactly.  Purely combinational (the
-- consumers' registers load only on their strobe).  Python model: golden.level_gain.
-- -----------------------------------------------------------------------------
library IEEE;
use IEEE.std_logic_1164.all;
use IEEE.numeric_std.all;

entity level_gain is
port(
      level : in  std_logic_vector(15 downto 0);        -- signed, Q8 log2 units
      mant  : out unsigned(16 downto 0);                -- 65536 .. 131071
      sh    : out natural range 14 to 20                 -- right shift of x * mant
     );
end entity;

